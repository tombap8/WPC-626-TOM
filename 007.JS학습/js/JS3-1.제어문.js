/***************************************** 
   [ for문 ]
    - 어떤 실행문을 순서대로 여러번 반복
    실행할 경우 사용하는 제어문

    ((구문구조))
    _____________________________________

    for(시;한;증){실행코드}
    - 시 -> 시작값(변수선언과 함께 숫자할당)
    - 한 -> 한계값(숫자를 조건문으로 사용)
    - 증 -> 증감(1씩증가 ++ / 1씩감소 --)

    ______________________________________

    ((구문해석))
    1. 먼저 시작값을 변수에 선언 후 할당함
    2. 중앙에 있는 한계값 조건에 맞는지 검사함
    3. 맞으면(true) for문의 중괄호{}안의 코드를 실행함
    4. 중괄호 안의 코드를 실행후 세번째 증감으로 감
        ++ / -- 로 1씩 증감함
    5. 중앙에 있는 한계값 조건에 맞는지 검사함
    6. 조건에 맞는 동안 중괄호 안의 코드를 실행함
    7. 중앙의 한계값 조건에 맞지 않으면(false)
        for문을 빠져나온다!

    ((참고 : 무한루프))
    for문의 범위를 잘못 설정하여 무한히
    for문을 돌게 되는 것을 무한루프에 빠졌다!
    라고 한다. 이때 최신 브라우저 엔진은
    범위에러로 처리하여 브라우저 자체가
    다운되지 않도록 처리한다!
*****************************************/



/******************************************** 
    함수명 : 와일구구단
    기능 : 각 단수에 맞는 구구단을 출력함
********************************************/
function 와일구구단(나야나){
  // 나야나 - this 로 함수호출시 보낸 select박스 자신!
  // 1. 함수호출확인
  console.log('구구단을 외자!!!', 나야나);

  // 2. 선택된 값 찍기
  // value는 선택된 option의 value값을 가져옴!
  // ((참고)) 만약 option에 value값이 없으면 option의 데이터값
  // 즉, 꺽쇠사이의 값을 읽어온다!
  let 몇단이니 = 나야나.value;
  console.log('선택된 값:', 몇단이니);

  // 3. 구구단 출력하기 ////
  // 대상: .gugu.g1
  let 구구단결과 = `<h2>${몇단이니}단</h2>`;

  // 시작값;
  // while(한계값){반복코드; 증감;}

  // 시작값
let i=1;
  while(i<=9){
    구구단결과 += 
    `${몇단이니} × ${i} ＝ ${몇단이니*i} <br>`;
    // 증감
    i++;
    // -> 만약 증감이 없으면 무한루프에 빠진다!
  } /// while ///


  // 4. 구구단 출력하기 : .g2에 출력! ////
  document.querySelector('.gugu.g2')
  .innerHTML = 구구단결과;

} // 와일구구단 함수 ///


/********************************************* 
   [ while문 ]

    - 반복실행코드를 위한 조건으로 만드는 제어문

    ((구문구조))
    ______________________________
    시작값;

    while(한계값){
        실행코드;
        증감;
    }
    ______________________________

    ((구문해석))

    - for문과 유사하나 시작값이 while문 윗쪽에 나옴
    - 한계값은 while문 소괄호 안에 씀
    - 증감은 while 실행코드 내부에 씀
    (주의: 증감을 안쓰면 무한루프에 빠짐!)

    - >>>>> while문과 for문은 무엇이 다른가?

    시작값과 증감없이 단지 조건에 의해서
    반복실행이 필요한 경우 사용할 수 있다!

    while(조건){코드}

    -> 예) 중복숫자 피하기, 직전값 피하기 등
    *********************************************/